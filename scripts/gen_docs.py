"""Generate a repo's reference documentation from its own source (ADR D-0018).

Reference facts (structure, routes, data model, component inventory) are derived by the static
extractors in ``gen_docs_extractors`` and written either to ``docs/reference/<name>.md`` (a
fully generated file) or into ``<!-- chrysa:docs:<name>:start -->`` ... ``:end -->`` blocks
that already exist inside a tracked markdown file. Nothing outside those two places is ever
touched. The target repo's code is never imported or executed.

Run ``python -m scripts.gen_docs`` to (re)write the docs, or ``python -m scripts.gen_docs
--check`` for the drift gate (the ``docs-drift`` pre-commit hook). A repo opts in with a
``docs:`` list in ``project-profile.yml``; without it, stack detection picks the extractors and
a *missing* generated file is not a failure.

Determinism is a contract (same as ``gen_context_files``): no timestamps, absolute paths or
random values in any generated byte.

Supported path: a git work tree (hook, CI, consumers). Without git (for example a
``git archive`` export checked in an image that has no git) the file list falls back to a
filesystem walk that skips hidden directories other than ``.github``/``.claude`` and
symlinks, so ``structure.md`` can read as stale although the committed file is right.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections.abc import Iterator
from pathlib import Path, PurePosixPath
from typing import NamedTuple

from scripts import gen_context_files
from scripts import gen_docs_extractors as extractors
from scripts.gen_docs_extractors import Extractor

try:  # pyyaml is optional: without it the profile is ignored and detection applies.
    import yaml
except ImportError:  # pragma: no cover - exercised only on hosts without pyyaml
    yaml = None

_ROOT = Path(__file__).resolve().parents[1]

REFERENCE_DIR = "docs/reference"
PROFILE = "project-profile.yml"
BANNER = (
    "<!-- GENERATED by scripts/gen_docs.py (ADR D-0018) — do not edit. "
    "Regenerate with `make gen-docs`. -->"
)
_MARKED = "chrysa:docs:"
MIN_PYTHON = (3, 12)
_BLOCK = re.compile(
    r"(?P<head><!-- chrysa:docs:(?P<name>[a-z-]+):start -->\r?\n)"
    r"(?P<body>(?:(?!<!-- chrysa:docs:[a-z-]+:start -->).)*?)"
    r"(?P<tail><!-- chrysa:docs:(?P=name):end -->)",
    re.DOTALL,
)
SOURCE_SUFFIXES = (".py", ".ts", ".tsx", ".js", ".jsx", ".go", ".rs", ".java", ".cs")
SKIP_PARTS = frozenset({"node_modules", ".venv", "venv", "dist", "build", "__pycache__", "vendor"})


class Expected(NamedTuple):
    """What a generated path must contain, and whether its absence counts as drift."""

    content: str
    required: bool


# ── selection ────────────────────────────────────────────────────────────────────────────


def project_files(root: Path) -> list[str]:
    """Repo files minus our own output, so generation is a fixed point (never self-listing)."""
    prefix = REFERENCE_DIR + "/"
    return [rel for rel in gen_context_files.repo_files(root) if not rel.startswith(prefix)]


def profile_extractors(root: Path) -> list[str] | None:
    """Extractor names listed under ``docs:`` in ``project-profile.yml``, or None if not opted in."""
    text = extractors.read_source(root, PROFILE)
    if yaml is None or text is None:
        return None
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError:
        return None
    names = data.get("docs") if isinstance(data, dict) else None
    if not isinstance(names, list):
        return None
    return sorted({str(name) for name in names})


def unknown_extractors(root: Path) -> list[str]:
    """Names in the profile that match no extractor."""
    listed = profile_extractors(root) or []
    return [name for name in listed if name not in extractors.BY_NAME]


def select(root: Path, files: list[str]) -> list[tuple[Extractor, bool]]:
    """Active extractors, each flagged True when the profile lists it explicitly."""
    listed = profile_extractors(root)
    if listed is not None:
        return [(extractors.BY_NAME[name], True) for name in listed if name in extractors.BY_NAME]
    return [(item, False) for item in extractors.EXTRACTORS if item.detect(root, files)]


# ── rendering ────────────────────────────────────────────────────────────────────────────


def _title(name: str) -> str:
    return name.replace("-", " ").capitalize()


def render_file(extractor: Extractor, root: Path, files: list[str]) -> str:
    """A fully generated ``docs/reference/<name>.md``."""
    return f"{BANNER}\n\n# {_title(extractor.name)}\n\n{extractor.render(root, files)}"


def read_raw(root: Path, rel: str) -> str | None:
    """File text decoded as UTF-8 with newlines untouched, or None if missing/undecodable."""
    if not extractors.is_safe_path(root, rel):
        return None
    try:
        return (root / rel).read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        return None


_FENCE = re.compile(r"^[ \t]*(?P<fence>`{3,}|~{3,})[^\n]*$", re.MULTILINE)


def fenced_regions(text: str) -> list[tuple[int, int]]:
    """Character spans of fenced code blocks (``` or ~~~); an unterminated fence runs to EOF.

    A fence closes on a line of the same character, at least as long, with nothing after it.
    """
    regions: list[tuple[int, int]] = []
    opened: tuple[int, str] | None = None
    for match in _FENCE.finditer(text):
        fence = match.group("fence")
        if opened is None:
            opened = (match.start(), fence)
        elif fence[0] == opened[1][0] and len(fence) >= len(opened[1]) and match.group(0).strip() == fence:
            regions.append((opened[0], match.end()))
            opened = None
    if opened is not None:
        regions.append((opened[0], len(text)))
    return regions


def _in_regions(position: int, regions: list[tuple[int, int]]) -> bool:
    return any(start <= position < end for start, end in regions)


def splice_blocks(text: str, bodies: dict[str, str]) -> str:
    """Replace the body of every complete marker block whose name has a generated body.

    Marker pairs inside fenced code blocks are examples, never live blocks, and are left alone.
    """
    out: list[str] = []
    last = 0
    fenced = fenced_regions(text)
    for match in _BLOCK.finditer(text):
        body = bodies.get(match.group("name"))
        if body is None or _in_regions(match.start(), fenced):
            continue
        out.append(text[last : match.start("body")])
        out.append(body.replace("\n", "\r\n") if "\r\n" in text else body)
        last = match.end("body")
    out.append(text[last:])
    return "".join(out)


def generate(root: Path) -> dict[str, Expected]:
    """Every path this generator owns, mapped to its expected content."""
    files = project_files(root)
    chosen = select(root, files)
    bodies = {item.name: item.render(root, files) for item, _ in chosen}
    expected = {
        f"{REFERENCE_DIR}/{item.name}.md": Expected(render_file(item, root, files), explicit)
        for item, explicit in chosen
    }
    for rel in files:
        text = read_raw(root, rel) if rel.endswith(".md") else None
        if text is None or _MARKED not in text:
            continue
        spliced = splice_blocks(text, bodies)
        if spliced != text:
            expected[rel] = Expected(spliced, True)
    return expected


def write_all(root: Path) -> None:
    """Write every owned path (bytes, so newlines never depend on the host)."""
    for rel, item in generate(root).items():
        if not extractors.is_safe_path(root, rel):
            sys.stderr.write(f"skipped symlinked path: {rel}\n")
            continue
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(item.content.encode("utf-8"))


# ── drift gate ───────────────────────────────────────────────────────────────────────────


def _unsafe_marked(root: Path) -> list[str]:
    """Tracked markdown files that carry markers but are symlinks or leave the root."""
    out: list[str] = []
    for rel in project_files(root):
        if not rel.endswith(".md") or extractors.is_safe_path(root, rel):
            continue
        try:
            marked = _MARKED in (root / rel).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if marked:
            out.append(f"unsafe path: {rel}")
    return out


def drift(root: Path) -> list[str]:
    """Drift lines (empty when every owned file is current)."""
    lines = [f"unknown extractor in {PROFILE}: {name}" for name in unknown_extractors(root)]
    lines += _unsafe_marked(root)
    for rel, item in sorted(generate(root).items()):
        if not extractors.is_safe_path(root, rel):
            lines.append(f"unsafe path: {rel}")
            continue
        actual = read_raw(root, rel)
        if actual is None:
            if item.required:
                lines.append(f"missing: {rel}")
        elif actual != item.content:
            lines.append(f"stale: {rel}")
    return lines


# ── git-aware checks ─────────────────────────────────────────────────────────────────────


class BaseRefError(ValueError):
    """The ``--base`` ref does not resolve to a commit (not fetched, or misspelled)."""


def _git_lines(root: Path, *args: str, sep: str = "\n") -> list[str] | None:
    """Non-empty output records of ``git -C root <args>`` split on ``sep`` (None on failure).

    Pass ``-z`` to git and ``sep="\0"`` for path lists: without it git quotes non-ASCII names.
    """
    try:
        result = subprocess.run(
            ["git", "-C", str(root), *args], capture_output=True, text=True, check=True
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return [line for line in result.stdout.split(sep) if line]


def _paths(root: Path, *args: str) -> list[str] | None:
    return _git_lines(root, *args, sep="\0")


def _diff_names(root: Path, base: str | None, kind: str) -> list[str] | None:
    """Paths of the change set filtered by ``kind`` (``A`` added, ``AM`` added/modified).

    None when ``root`` is not a git work tree; BaseRefError when ``base`` does not resolve.
    ``base`` is compared to HEAD directly, so it should be the merge-base of the branch.
    Renames are disabled so a moved file counts as added at its new path.
    """
    if _git_lines(root, "rev-parse", "--is-inside-work-tree") is None:
        return None
    if base is not None and _git_lines(root, "rev-parse", "--verify", "--quiet", f"{base}^{{commit}}") is None:
        raise BaseRefError(base)
    scope = ["--cached"] if base is None else [base, "HEAD"]
    return _paths(
        root, "diff", "-z", "--name-only", "--no-renames", f"--diff-filter={kind}", *scope
    )


def is_source(path: str) -> bool:
    """A source file outside vendored, hidden and build directories."""
    parent_parts = path.split("/")[:-1]
    if any(part in SKIP_PARTS or part.startswith(".") for part in parent_parts):
        return False
    return path.endswith(SOURCE_SUFFIXES)


def _ancestors(path: str) -> Iterator[str]:
    """Every parent directory of ``path`` (``a/b/c.py`` yields ``a/b`` then ``a``)."""
    for parent in PurePosixPath(path).parents:
        if str(parent) != ".":
            yield str(parent)


def _tracked(root: Path, ref: str) -> list[str]:
    """Tracked paths in the tree of ``ref`` (empty when ref does not exist, e.g. no commit yet)."""
    return _paths(root, "ls-tree", "-r", "-z", "--name-only", ref) or []


def _dirs_at(root: Path, ref: str) -> set[str]:
    """Every directory that held a tracked file at ``ref``."""
    return {parent for rel in _tracked(root, ref) for parent in _ancestors(rel)}


def new_dirs_missing_readme(root: Path, base: str | None = None) -> list[str]:
    """Newly created directories that directly hold a source file and carry no README.md.

    A README counts only when it belongs to the compared change set (staged index, or the HEAD
    tree in base mode), never a stray untracked file. Raises BaseRefError on an unknown base.
    """
    added = _diff_names(root, base, "A")
    if added is None:
        return []
    existing = _dirs_at(root, base or "HEAD")
    present = set(_paths(root, "ls-files", "-z") or []) if base is None else set(_tracked(root, "HEAD"))
    missing: set[str] = set()
    for rel in added:
        directory = str(PurePosixPath(rel).parent)
        if directory == "." or directory in existing or not is_source(rel):
            continue
        if f"{directory}/README.md" not in present:
            missing.add(directory)
    return sorted(missing)


def changed_files(root: Path, base: str | None = None) -> list[str]:
    """Added or modified paths in the change set (empty when git is unavailable)."""
    return _diff_names(root, base, "AM") or []


def docs_warning(changed: list[str], active: list[Extractor]) -> str | None:
    """Non-blocking hint: covered source changed while no documentation did."""
    covered = sorted(path for path in changed if any(item.covers(path) for item in active))
    touched_docs = any(path.endswith(".md") or path.startswith("docs/") for path in changed)
    if not covered or touched_docs:
        return None
    return (
        f"warning: {len(covered)} source file(s) covered by the reference docs changed but no "
        f"documentation was touched (first: {covered[0]})"
    )


def check(root: Path, base: str | None = None) -> int:
    """Run the gate: print problems to stderr and return the process exit code."""
    problems = drift(root)
    warning = None
    try:
        problems += [
            f"new folder without README.md: {directory}/"
            for directory in new_dirs_missing_readme(root, base)
        ]
        active = [item for item, _ in select(root, project_files(root))]
        warning = docs_warning(changed_files(root, base), active)
    except BaseRefError as error:
        problems.append(f"cannot resolve base ref: {error}")
    if warning:
        sys.stderr.write(warning + "\n")
    if not problems:
        return 0
    sys.stderr.write("reference docs check failed:\n")
    for line in problems:
        sys.stderr.write(f"  - {line}\n")
    sys.stderr.write(
        "run `make gen-docs` (or `python -m scripts.gen_docs`) and commit the result.\n"
    )
    return 1


def main(argv: list[str] | None = None, root: Path = _ROOT) -> int:
    """CLI entry point: regenerate, or ``--check`` for the drift gate."""
    parser = argparse.ArgumentParser(description="Generate reference docs from source.")
    parser.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    parser.add_argument("--base", default=None, help="base ref for the new-folder check")
    args = parser.parse_args(argv)
    if sys.version_info < MIN_PYTHON:
        sys.stderr.write(
            "gen_docs needs Python >= 3.12 (frozen runtime is 3.14): output depends on the "
            "grammar that parses the target's sources.\n"
        )
        return 2
    if not args.check:
        write_all(root)
        return 0
    return check(root, args.base)


if __name__ == "__main__":
    raise SystemExit(main())
