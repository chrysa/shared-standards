"""Generate a repo's reference documentation from its own source (ADR D-0018).

Reference facts (structure, routes, data model, component inventory) are derived by the static
extractors in ``gen_docs_extractors`` and written either to ``docs/reference/<name>.md`` (a
fully generated file) or into ``<!-- chrysa:docs:<name>:start -->`` ... ``:end -->`` blocks
that already exist inside a tracked markdown file. Nothing outside those two places is ever
touched. The target repo's code is never imported or executed.

Run ``python -m scripts.gen_docs`` to (re)write the docs, or ``python -m scripts.gen_docs
--check`` for the drift gate (the ``docs-drift`` pre-commit hook). A repo opts in with a
``docs:`` list in ``project-profile.yml``; without it, stack detection picks the extractors and
a *missing* generated file is not a failure.

Determinism is a contract (same as ``gen_context_files``): no timestamps, absolute paths or
random values in any generated byte.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import NamedTuple

from scripts import gen_context_files
from scripts import gen_docs_extractors as extractors
from scripts.gen_docs_extractors import Extractor

try:  # pyyaml is optional: without it the profile is ignored and detection applies.
    import yaml
except ImportError:  # pragma: no cover - exercised only on hosts without pyyaml
    yaml = None

_ROOT = Path(__file__).resolve().parents[1]

REFERENCE_DIR = "docs/reference"
PROFILE = "project-profile.yml"
BANNER = (
    "<!-- GENERATED by scripts/gen_docs.py (ADR D-0018) — do not edit. "
    "Regenerate with `make gen-docs`. -->"
)
_MARKED = "chrysa:docs:"
_BLOCK = re.compile(
    r"(?P<head><!-- chrysa:docs:(?P<name>[a-z-]+):start -->\r?\n)"
    r"(?P<body>(?:(?!<!-- chrysa:docs:[a-z-]+:start -->).)*?)"
    r"(?P<tail><!-- chrysa:docs:(?P=name):end -->)",
    re.DOTALL,
)


class Expected(NamedTuple):
    """What a generated path must contain, and whether its absence counts as drift."""

    content: str
    required: bool


# ── selection ────────────────────────────────────────────────────────────────────────────


def project_files(root: Path) -> list[str]:
    """Repo files minus our own output, so generation is a fixed point (never self-listing)."""
    prefix = REFERENCE_DIR + "/"
    return [rel for rel in gen_context_files.repo_files(root) if not rel.startswith(prefix)]


def profile_extractors(root: Path) -> list[str] | None:
    """Extractor names listed under ``docs:`` in ``project-profile.yml``, or None if not opted in."""
    text = extractors.read_source(root, PROFILE)
    if yaml is None or text is None:
        return None
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError:
        return None
    names = data.get("docs") if isinstance(data, dict) else None
    if not isinstance(names, list):
        return None
    return sorted({str(name) for name in names})


def unknown_extractors(root: Path) -> list[str]:
    """Names in the profile that match no extractor."""
    listed = profile_extractors(root) or []
    return [name for name in listed if name not in extractors.BY_NAME]


def select(root: Path, files: list[str]) -> list[tuple[Extractor, bool]]:
    """Active extractors, each flagged True when the profile lists it explicitly."""
    listed = profile_extractors(root)
    if listed is not None:
        return [(extractors.BY_NAME[name], True) for name in listed if name in extractors.BY_NAME]
    return [(item, False) for item in extractors.EXTRACTORS if item.detect(root, files)]


# ── rendering ────────────────────────────────────────────────────────────────────────────


def _title(name: str) -> str:
    return name.replace("-", " ").capitalize()


def render_file(extractor: Extractor, root: Path, files: list[str]) -> str:
    """A fully generated ``docs/reference/<name>.md``."""
    return f"{BANNER}\n\n# {_title(extractor.name)}\n\n{extractor.render(root, files)}"


def read_raw(root: Path, rel: str) -> str | None:
    """File text decoded as UTF-8 with newlines untouched, or None if missing/undecodable."""
    try:
        return (root / rel).read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def splice_blocks(text: str, bodies: dict[str, str]) -> str:
    """Replace the body of every complete marker block whose name has a generated body."""
    out: list[str] = []
    last = 0
    for match in _BLOCK.finditer(text):
        body = bodies.get(match.group("name"))
        if body is None:
            continue
        out.append(text[last : match.start("body")])
        out.append(body.replace("\n", "\r\n") if "\r\n" in text else body)
        last = match.end("body")
    out.append(text[last:])
    return "".join(out)


def generate(root: Path) -> dict[str, Expected]:
    """Every path this generator owns, mapped to its expected content."""
    files = project_files(root)
    chosen = select(root, files)
    bodies = {item.name: item.render(root, files) for item, _ in chosen}
    expected = {
        f"{REFERENCE_DIR}/{item.name}.md": Expected(render_file(item, root, files), explicit)
        for item, explicit in chosen
    }
    for rel in files:
        text = read_raw(root, rel) if rel.endswith(".md") else None
        if text is None or _MARKED not in text:
            continue
        spliced = splice_blocks(text, bodies)
        if spliced != text:
            expected[rel] = Expected(spliced, True)
    return expected


def write_all(root: Path) -> None:
    """Write every owned path (bytes, so newlines never depend on the host)."""
    for rel, item in generate(root).items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(item.content.encode("utf-8"))


# ── drift gate ───────────────────────────────────────────────────────────────────────────


def drift(root: Path) -> list[str]:
    """Drift lines (empty when every owned file is current)."""
    lines = [f"unknown extractor in {PROFILE}: {name}" for name in unknown_extractors(root)]
    for rel, item in sorted(generate(root).items()):
        actual = read_raw(root, rel)
        if actual is None:
            if item.required:
                lines.append(f"missing: {rel}")
        elif actual != item.content:
            lines.append(f"stale: {rel}")
    return lines


def check(root: Path, base: str | None = None) -> int:  # noqa: ARG001  (base used from Task 4)
    """Run the gate: print problems to stderr and return the process exit code."""
    problems = drift(root)
    if not problems:
        return 0
    sys.stderr.write("reference docs check failed:\n")
    for line in problems:
        sys.stderr.write(f"  - {line}\n")
    sys.stderr.write(
        "run `make gen-docs` (or `python -m scripts.gen_docs`) and commit the result.\n"
    )
    return 1


def main(argv: list[str] | None = None, root: Path = _ROOT) -> int:
    """CLI entry point: regenerate, or ``--check`` for the drift gate."""
    parser = argparse.ArgumentParser(description="Generate reference docs from source.")
    parser.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    parser.add_argument("--base", default=None, help="base ref for the new-folder check")
    args = parser.parse_args(argv)
    if not args.check:
        write_all(root)
        return 0
    return check(root, args.base)


if __name__ == "__main__":
    raise SystemExit(main())
